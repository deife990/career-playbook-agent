// Run with sharp available in NODE_PATH. No runtime dependency is added to the game.
'use strict';
const fs=require('node:fs/promises'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const sharp=require('sharp');
const root=path.resolve(__dirname,'..'),assetRoot=path.join(root,'assets/reference-ui');
const digest=data=>crypto.createHash('sha256').update(data).digest('hex');
async function main(){
  const tutorial=vm.runInNewContext(await fs.readFile(path.join(root,'src/tutorial/tutorial.js'),'utf8')+';CP_TUTORIAL');
  const output=path.join(assetRoot,'upscaled');await fs.mkdir(output,{recursive:true});
  const frames={},sources={};let totalBytes=0;
  for(const [service,steps] of Object.entries(tutorial.services))for(const [index,item] of steps.entries()){
    const source=await fs.readFile(path.join(assetRoot,item.file)),meta=await sharp(source).metadata();
    if(meta.width!==item.size[0]||meta.height!==item.size[1])throw Error('Source dimensions changed: '+item.file);
    sources[item.file]={width:meta.width,height:meta.height,sha256:digest(source)};
    const [left,top,width,height]=item.crop;
    if(left<0||top<0||left+width>meta.width||top+height>meta.height)throw Error('Invalid crop: '+item.file);
    const candidates=[];
    for(const scale of [1,2,4]){
      const file=service.toLowerCase()+'-'+String(index+1).padStart(2,'0')+'@'+scale+'x.webp';
      let pipeline=sharp(source).extract({left,top,width,height}).toColourspace('srgb');
      if(scale>1)pipeline=pipeline.resize(width*scale,height*scale,{kernel:sharp.kernel.lanczos3}).sharpen({sigma:.45,m1:0,m2:.6});
      const data=await pipeline.webp({lossless:true,effort:6}).toBuffer();
      await fs.writeFile(path.join(output,file),data);totalBytes+=data.length;
      candidates.push({url:'reference-ui/upscaled/'+file,scale,width:width*scale,height:height*scale,bytes:data.length,sha256:digest(data)});
    }
    frames[item.file+'@'+item.crop.join(',')]={source:item.file,crop:item.crop,candidates};
  }
  await fs.writeFile(path.join(root,'src/content/capture-assets.js'),"'use strict';\n// Generated by tools/build-tutorial-images.cjs. Crop geometry remains in original pixels.\nconst CP_CAPTURE_ASSETS = "+JSON.stringify(frames,null,2)+';\n');
  const manifest={generatedAt:new Date().toISOString(),method:'Deterministic Lanczos3 2x/4x resampling, mild edge sharpening (sigma .45, m1 0, m2 .6), lossless WebP; 1x crop has no resizing or sharpening. No generative reconstruction.',sources,frames,totalBytes};
  await fs.writeFile(path.join(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log(JSON.stringify({sourceImages:Object.keys(sources).length,displayRegions:Object.keys(frames).length,variants:Object.keys(frames).length*3,totalBytes,passed:true}));
}
main().catch(error=>{console.error(error);process.exitCode=1;});
